// Regenerates docs/agents.md and docs/skills.md from the agent and skill registries (run after `npm run build`).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const { MagecRuntime } = await import(join(root, 'apps/runtime/dist/index.js'));
const rt = await MagecRuntime.create({ projectDir: root, stderr: false });

let agents = '# Agents\n\n<!-- generated by scripts/gen-docs.mjs; edit agents/*/agent.json and AGENT.md instead -->\n\n';
agents += 'Each agent is `agents/<id>/agent.json` (contract: permissions, skills, task types, outputs) plus `AGENT.md` (operating instructions). Permissions are enforced by the runtime tool registry; skills grant no permissions.\n\n';
agents += '| Agent | Kind | Task types | Permissions | Model tier |\n|---|---|---|---|---|\n';
for (const a of rt.agents.list()) {
  const d = a.definition;
  agents += `| \`${d.id}\` | ${d.kind} | ${d.taskTypes.join(', ')} | ${d.permissions.join(', ')} | ${d.model.tier} |\n`;
}
for (const a of rt.agents.list()) {
  const d = a.definition;
  agents += `\n## ${d.name} (\`${d.id}\`)\n\n${d.description}\n\n**Responsibilities**\n${d.responsibilities.map((r) => `- ${r}`).join('\n')}\n\n`;
  agents += `**Outputs:** ${d.outputs.map((o) => `${o.description}${o.schema ? ` (${o.schema})` : ''}`).join('; ')}\n\n`;
  agents += `**Skills:** shared — ${d.skills.shared.join(', ')}; specialized — ${d.skills.specialized.join(', ')}\n\n`;
  agents += `**Runtime tools allowed (${rt.tools.allowedFor(d.id).length}):** ${rt.tools.allowedFor(d.id).map((t) => `\`${t.name}\``).join(', ')}\n`;
}
writeFileSync(join(root, 'docs/agents.md'), agents);

let skills = '# Skills\n\n<!-- generated by scripts/gen-docs.mjs -->\n\n';
skills += 'Skills live in `skills/shared/<name>/SKILL.md` (usable by any agent) and `skills/specialized/<name>/SKILL.md` (owned by the agents listed in their frontmatter). The registry discovers them at startup, validates frontmatter, required sections, owners and referenced tools, and agents load full instructions on demand with `magec_skill_load`. Only metadata is placed in an agent\'s prompt.\n\n';
skills += 'Required sections: Purpose, When to use, Inputs, Outputs, Tool requirements, Instructions, Constraints, Validation, Error handling, Related.\n\n';
for (const cat of ['shared', 'specialized']) {
  skills += `## ${cat === 'shared' ? 'Shared' : 'Specialized'} skills\n\n| Skill | ${cat === 'specialized' ? 'Owner | ' : ''}Description |\n|---|${cat === 'specialized' ? '---|' : ''}---|\n`;
  for (const s of rt.skills.list({ category: cat })) skills += `| \`${s.name}\` | ${cat === 'specialized' ? `${s.agents.join(', ')} | ` : ''}${s.description.replace(/\|/g, '\\|')} |\n`;
  skills += '\n';
}
writeFileSync(join(root, 'docs/skills.md'), skills);
await rt.close();
console.log('docs/agents.md and docs/skills.md regenerated');
